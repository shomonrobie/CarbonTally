@router.post("/", response_model=GlossaryTermResponse)
async def create_glossary_term(
    term_data: GlossaryTermCreate,
    current_user: AuthUser = Depends(require_role(["admin", "data_approver"]))
):
    """
    Create a new glossary term.
    Admin or Data Approver only endpoint.
    """
    try:
        supabase = get_supabase_client()
        
        # Check if client is initialized
        if supabase is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Supabase client not initialized"
            )
        
        # Check if term already exists
        existing = supabase.from_('glossary') \
            .select('id') \
            .eq('term', term_data.term) \
            .maybe_single() \
            .execute()
        
        # Handle None response
        if existing is None:
            print("⚠️ Warning: existing query returned None")
            # Continue anyway - we'll try to create
        elif existing.data:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail=f"Term '{term_data.term}' already exists"
            )
        
        # Create term
        now = datetime.now().isoformat()
        result = supabase.from_('glossary') \
            .insert({
                'term': term_data.term,
                'definition': term_data.definition,
                'category': term_data.category,
                'related_terms': term_data.related_terms,
                'example': term_data.example,
                'is_active': True,
                'created_at': now,
                'updated_at': now
            }) \
            .execute()
        
        # Check result
        if result is None:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Database insert returned None"
            )
            
        if not result.data:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to create glossary term - no data returned"
            )
        
        term = result.data[0]
        return GlossaryTermResponse(
            id=term['id'],
            term=term['term'],
            definition=term['definition'],
            category=term.get('category'),
            related_terms=term.get('related_terms'),
            example=term.get('example'),
            is_active=term.get('is_active', True),
            created_at=term['created_at'],
            updated_at=term['updated_at']
        )
        
    except HTTPException:
        raise
    except Exception as e:
        print(f"❌ Error creating glossary term: {e}")
        import traceback
        traceback.print_exc()
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to create glossary term: {str(e)}"
        )


@router.put("/{term_id}", response_model=GlossaryTermResponse)
async def update_glossary_term(
    term_id: str,
    term_data: GlossaryTermUpdate,
    current_user: AuthUser = Depends(require_role(["admin", "data_approver"]))  # ✅ Called here
):
    """
    Update a glossary term.
    Admin or Data Approver only endpoint.
    """
    try:
        supabase = get_supabase_client()
        
        # Check if term exists
        existing = supabase.from_('glossary') \
            .select('id, term') \
            .eq('id', term_id) \
            .maybe_single() \
            .execute()
        
        if not existing.data:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Term not found"
            )
        
        # Build update dict
        update_dict = {}
        if term_data.term is not None:
            # Check if new term name conflicts
            if term_data.term != existing.data['term']:
                conflict = supabase.from_('glossary') \
                    .select('id') \
                    .eq('term', term_data.term) \
                    .neq('id', term_id) \
                    .maybe_single() \
                    .execute()
                
                if conflict.data:
                    raise HTTPException(
                        status_code=status.HTTP_409_CONFLICT,
                        detail=f"Term '{term_data.term}' already exists"
                    )
            update_dict['term'] = term_data.term
        
        if term_data.definition is not None:
            update_dict['definition'] = term_data.definition
        if term_data.category is not None:
            update_dict['category'] = term_data.category
        if term_data.related_terms is not None:
            update_dict['related_terms'] = term_data.related_terms
        if term_data.example is not None:
            update_dict['example'] = term_data.example
        
        if not update_dict:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="No fields to update"
            )
        
        update_dict['updated_at'] = datetime.now().isoformat()
        
        # Update term
        result = supabase.from_('glossary') \
            .update(update_dict) \
            .eq('id', term_id) \
            .execute()
        
        if not result.data:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to update glossary term"
            )
        
        term = result.data[0]
        return GlossaryTermResponse(
            id=term['id'],
            term=term['term'],
            definition=term['definition'],
            category=term.get('category'),
            related_terms=term.get('related_terms'),
            example=term.get('example'),
            is_active=term.get('is_active', True),
            created_at=term['created_at'],
            updated_at=term['updated_at']
        )
        
    except HTTPException:
        raise
    except Exception as e:
        print(f"❌ Error updating glossary term: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to update glossary term: {str(e)}"
        )

@router.delete("/{term_id}")
async def delete_glossary_term(
    term_id: str,
    permanent: bool = Query(False, description="Permanently delete or soft delete"),
    current_user: AuthUser = Depends(require_role(["admin"]))  # ✅ Called here
):
    """
    Delete a glossary term.
    Admin only endpoint.
    """
    try:
        supabase = get_supabase_client()
        
        # Check if term exists
        existing = supabase.from_('glossary') \
            .select('id, term') \
            .eq('id', term_id) \
            .maybe_single() \
            .execute()
        
        if not existing.data:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Term not found"
            )
        
        term_name = existing.data['term']
        
        if permanent:
            # Hard delete
            result = supabase.from_('glossary') \
                .delete() \
                .eq('id', term_id) \
                .execute()
            
            message = f"Term '{term_name}' permanently deleted"
        else:
            # Soft delete
            result = supabase.from_('glossary') \
                .update({
                    'is_active': False,
                    'updated_at': datetime.now().isoformat()
                }) \
                .eq('id', term_id) \
                .execute()
            
            message = f"Term '{term_name}' deactivated"
        
        return {
            "success": True,
            "message": message,
            "term_id": term_id,
            "term_name": term_name,
            "permanent": permanent
        }
        
    except HTTPException:
        raise
    except Exception as e:
        print(f"❌ Error deleting glossary term: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to delete glossary term: {str(e)}"
        )

@router.post("/{term_id}/restore")
async def restore_glossary_term(
    term_id: str,
    current_user: AuthUser = Depends(require_role(["admin"]))  # ✅ Called here
):
    """
    Restore a soft-deleted glossary term.
    Admin only endpoint.
    """
    try:
        supabase = get_supabase_client()
        
        # Check if term exists and is inactive
        existing = supabase.from_('glossary') \
            .select('id, term') \
            .eq('id', term_id) \
            .eq('is_active', False) \
            .maybe_single() \
            .execute()
        
        if not existing.data:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Inactive term not found"
            )
        
        # Restore term
        result = supabase.from_('glossary') \
            .update({
                'is_active': True,
                'updated_at': datetime.now().isoformat()
            }) \
            .eq('id', term_id) \
            .execute()
        
        return {
            "success": True,
            "message": f"Term '{existing.data['term']}' restored successfully",
            "term_id": term_id
        }
        
    except HTTPException:
        raise
    except Exception as e:
        print(f"❌ Error restoring glossary term: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to restore glossary term: {str(e)}"
        )
        
async def get_available_categories(supabase_client) -> List[str]:
    """Get all available categories from glossary."""
    try:
        result = supabase_client.from_('glossary') \
            .select('category') \
            .eq('is_active', True) \
            .execute()
        
        categories = list(set([t.get('category') for t in result.data if t.get('category')])) if result.data else []
        return sorted(categories)
    except Exception as e:
        print(f"⚠️ Error getting categories: {e}")
        return []


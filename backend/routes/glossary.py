@router.get("/", response_model=GlossaryListResponse)
async def get_glossary(
    category: Optional[str] = Query(None, description="Filter by category"),
    search: Optional[str] = Query(None, description="Search in term and definition"),
    limit: int = Query(100, ge=1, le=500, description="Number of results to return"),
    offset: int = Query(0, ge=0, description="Number of results to skip")
):
    """
    Get all glossary terms with optional filtering.
    Public endpoint - no authentication required.
    """
    try:
        supabase = get_supabase_client()
        
        # Build query
        query = supabase.from_('glossary') \
            .select('*') \
            .eq('is_active', True)
        
        # Apply filters
        if category:
            query = query.eq('category', category)
        
        if search:
            query = query.or_(f"term.ilike.%{search}%,definition.ilike.%{search}%")
        
        # ✅ Fix: Remove .clone() and use separate count query
        count_query = supabase.from_('glossary') \
            .select('id', count='exact') \
            .eq('is_active', True)
        
        if category:
            count_query = count_query.eq('category', category)
        
        if search:
            count_query = count_query.or_(f"term.ilike.%{search}%,definition.ilike.%{search}%")
        
        count_result = count_query.execute()
        total = count_result.count or 0
        
        # Get paginated results
        result = query.order('term') \
            .range(offset, offset + limit - 1) \
            .execute()
        
        # Transform data
        terms = []
        for term in (result.data or []):
            terms.append(GlossaryTermResponse(
                id=term['id'],
                term=term['term'],
                definition=term['definition'],
                category=term.get('category'),
                related_terms=term.get('related_terms'),
                example=term.get('example'),
                is_active=term.get('is_active', True),
                created_at=term['created_at'],
                updated_at=term.get('updated_at', term['created_at'])
            ))
        
        # Get available categories
        categories = await get_available_categories(supabase) if not category else [category]
        
        return GlossaryListResponse(
            success=True,
            data=terms,
            total=total,
            categories=categories
        )
        
    except Exception as e:
        print(f"❌ Error getting glossary: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to get glossary: {str(e)}"
        )




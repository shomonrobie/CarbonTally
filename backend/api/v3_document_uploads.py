# completion (verification + security gate)
# ---------------------------------------------------------------------------


async def _complete_upload(
    *,
    actor: UploadActor,
    repos: Any,
    document_id: str,
    client_id: Optional[str] = None,
) -> dict:
    """Verify a browser-completed direct upload and run the security gate."""
    doc = await repos.files.get(document_id)
    if doc is None:
        raise HTTPException(status_code=404, detail="document not found")

    doc_organization = str(_attr(doc, "organization_id") or "")
    if doc_organization != actor.organization_id:
        await record_document_event(
            repos=repos,
            action=ACTION_DOWNLOAD,
            actor=actor,
            organization_id=actor.organization_id,
            entity_id=document_id,
            changed_fields={"document_organization_id": doc_organization},
            reason="upload completion refused: document belongs to another organisation",
            outcome="failure",
        )
        raise HTTPException(status_code=403, detail="Organization access denied")

    current_status = _attr(doc, "status")
    if current_status in (STATUS_CLEAN, STATUS_PROCESSING):
        return {
            "document_id": document_id,
            "status": current_status,
            "idempotent": True,
            "client_id": client_id,
            # The verdict recorded when the upload was started, so a re-entrant
            # completion reports the same classification as the first one.
            "classification": dict(_attr(doc, "metadata") or {}).get("classification")
            or _unavailable_classification(),
        }
    if current_status != STATUS_PENDING_UPLOAD:
        raise HTTPException(
            status_code=409,
            detail=(
                f"document is in status '{current_status}' and cannot be completed; "
                "only a pending upload can be completed"
            ),
        )
    if _upload_window_expired(doc):
        raise HTTPException(
            status_code=409,
            detail=(
                "the upload authorisation has expired; nothing was accepted — "
                "start a new upload"
            ),
        )

    path = str(_attr(doc, "path") or "")
    filename = str(_attr(doc, "name") or "")
    if not key_belongs_to_organization(path, doc_organization):
        raise HTTPException(
            status_code=409,
            detail=(
                "the document's storage path is not a canonical CarbonTally "
                "document key for this organisation; nothing was accepted"
            ),
        )
    limit_mb, limit_bytes = await _effective_limit_bytes(repos)

    info = object_info(path)
    if info is None:
        raise HTTPException(
            status_code=409,
            detail="no object was found at the upload target; nothing was accepted",
        )
    actual_size = stored_object_size(info)
    if not actual_size:
        await _set_document_status(repos, document_id, STATUS_REJECTED)
        await record_document_event(
            repos=repos,
            action=ACTION_SECURITY_REJECTED,
            actor=actor,
            organization_id=doc_organization,
            entity_id=document_id,
            changed_fields={"storage_path": path, "storage_info": info},
            reason="malformed or truncated upload: the stored object has no usable size",
            outcome="failure",
        )
        raise HTTPException(
            status_code=409,
            detail="the uploaded object is empty or truncated; nothing was accepted",
        )
    if actual_size > limit_bytes:
        await _set_document_status(repos, document_id, STATUS_REJECTED)
        await record_document_event(
            repos=repos,
            action=ACTION_SECURITY_REJECTED,
            actor=actor,
            organization_id=doc_organization,
            entity_id=document_id,
            changed_fields={"storage_path": path, "actual_size_bytes": actual_size},
            reason=_oversize_detail(filename, actual_size, limit_mb),
            outcome="failure",
        )
        raise HTTPException(
            status_code=413, detail=_oversize_detail(filename, actual_size, limit_mb)
        )

    await record_document_event(
        repos=repos,
        action=ACTION_SECURITY_SCAN_STARTED,
        actor=actor,
        organization_id=doc_organization,
        entity_id=document_id,
        changed_fields={"storage_path": path, "actual_size_bytes": actual_size},
        reason="security gate started after the direct upload completed",
    )
    probed = None
    try:
        probed = download_object(path, max_bytes=limit_bytes)
    except TypeError:  # pragma: no cover - a legacy single-argument double
        probed = download_object(path)
    if probed is None:
        probed = download_object_prefix(path)
    if probed is None:
        raise HTTPException(
            status_code=409,
            detail="the uploaded object could not be read back; nothing was accepted",
        )
    # Step 2J — the same bytes feed BOTH the security gate and the downstream
    # processing pipeline, so a directly-uploaded document receives exactly the
    # same page count and OCR prefill as a server-proxied upload.  The read is
    # bounded by the ratified per-file ceiling and nothing is written back, so
    # the stored object remains the customer's unmodified original evidence.
    verdict = scan_document(
        content=probed,
        filename=filename,
        declared_mime=str(_attr(doc, "mime_type") or ""),
        extension=split_extension(filename),
    )
    await record_document_event(
        repos=repos,
        action=ACTION_SECURITY_SCAN_COMPLETED,
        actor=actor,
        organization_id=doc_organization,
        entity_id=document_id,
        changed_fields={"security_gate": verdict.as_metadata()},
        reason=f"security gate verdict: {verdict.verdict}",
        outcome="success" if verdict.accepted else "failure",
    )
    if not verdict.accepted:
        await _set_document_status(repos, document_id, STATUS_REJECTED)
        await record_document_event(
            repos=repos,
            action=ACTION_SECURITY_REJECTED,
            actor=actor,
            organization_id=doc_organization,
            entity_id=document_id,
            changed_fields={
                "security_gate": verdict.as_metadata(),
                "storage_path": path,
            },
            reason=rejection_detail(verdict),
            outcome="failure",
        )
        # Step 2D — say exactly WHY a required scan could not be established,
        # rather than reporting a generic rejection or (worse) an acceptance.
        if verdict.scan_state in (
            SCAN_STATE_SCANNER_UNAVAILABLE,
            SCAN_STATE_SCANNER_ERROR,
        ):
            await record_document_event(
                repos=repos,
                action=ACTION_SCAN_UNAVAILABLE,
                actor=actor,
                organization_id=doc_organization,
                entity_id=document_id,
                changed_fields={
                    "scan_state": verdict.scan_state,
                    "scanner": verdict.scanner,
                    "scanner_error": verdict.scanner_error,
                    "document_status": STATUS_REJECTED,
                },
                reason=(
                    "the document is quarantined because the required malware "
                    "scan could not be obtained; no malware-free status is claimed"
                ),
                outcome="failure",
            )
        raise HTTPException(status_code=422, detail=rejection_detail(verdict))

    await _set_document_status(repos, document_id, STATUS_CLEAN, actual_size)
    await record_document_event(
        repos=repos,
        action=ACTION_UPLOAD_COMPLETED,
        actor=actor,
        organization_id=doc_organization,
        entity_id=document_id,
        changed_fields={
            "storage_path": path,
            "bucket": DOCUMENTS_BUCKET,
            "actual_size_bytes": actual_size,
            "status": STATUS_CLEAN,
        },
        reason="direct upload verified and accepted by the security gate",
    )
    await record_document_event(
        repos=repos,
        action=ACTION_ACCEPTED,
        actor=actor,
        organization_id=doc_organization,
        entity_id=document_id,
        changed_fields={"status": STATUS_CLEAN, "filename": filename},
        reason="document accepted for normal CarbonTally processing",
    )

    # Only a security-cleared document enters the durable processing pipeline.
    merged_metadata = dict(_attr(doc, "metadata") or {})
    merged_metadata["security_gate"] = verdict.as_metadata()
    merged_metadata["verified_size_bytes"] = actual_size
    # CT-PO-UPLOAD-UNIFY-001 — the classification decided at initiation is carried
    # through to the completion payload.  It is metadata only: the processing
    # pipeline is enqueued with exactly the same arguments as before.
    classification = merged_metadata.get("classification") or _unavailable_classification()
    try:
        await repos.files.update_metadata(document_id, merged_metadata)
    except Exception as exc:  # noqa: BLE001 - metadata write is best-effort
        print(f"could not record the security verdict on {document_id}: {exc!r}")
    # Step 2J — pass the verified bytes so the shared pipeline computes the real
    # page count and runs the OCR prefill exactly as it does for a proxied
    # upload.  The identical downstream semantics are the point: a direct upload
    # must not silently lose processing functionality.
    await enqueue_document_processing(
        record={"id": document_id, "metadata": merged_metadata},
        document_id=document_id,
        organization_id=doc_organization,
        filename=filename,
        content=probed,
        mime_type=str(_attr(doc, "mime_type") or "application/octet-stream"),
        file_type=str(_attr(doc, "file_type") or "OTHER"),
        data_type=str(merged_metadata.get("data_type") or "utility"),
        uploaded_by=actor.user_id,
        repos=repos,
        storage_path=path,
    )

    # Step 2N — refresh the EXISTING storage-metering snapshot so the
    # admin-configurable capacity (billing_plans.included_storage_bytes) sees
    # this document.  Best-effort by design: commercial metering must never fail
    # an accepted upload, and capacity is metered/billed rather than enforced as
    # an upload block (see services.storage_metering).
    metering: dict = {}
    try:
        from services.storage_metering import record_storage_usage

        metering = await record_storage_usage(repos, doc_organization)
    except Exception as exc:  # noqa: BLE001 - never fail an accepted upload
        metering = {"recorded": False, "reason": str(exc)[:200]}

    return {
        "document_id": document_id,
        "organization_id": doc_organization,
        "client_id": client_id,
        "bucket": DOCUMENTS_BUCKET,
        "storage_path": path,
        "filename": filename,
        "status": STATUS_CLEAN,
        "size_bytes": actual_size,
        "security_gate": verdict.as_metadata(),
        "scan_state": verdict.scan_state,
        "external_scan_available": verdict.external_scan_available,
        "virus_scanned": verdict.external_scan_claimed(),
        "storage_metering": metering,
        "classification": classification,
        "idempotent": False,
    }



async def _start_upload(
    *,
    actor: UploadActor,
    repos: Any,
    filename: str,
    size_bytes: int,
    content_type: str,
    data_type: str,
    completion_path: str,
    client_id: Optional[str] = None,
    document_type_code: Optional[str] = None,
) -> dict:
    """Validate, record the pending document, and issue the signed upload URL."""
    if not is_safe_filename(filename):
        raise HTTPException(
            status_code=422,
            detail=(
                "the file name contains path separators or control characters; "
                "the storage object name is generated by CarbonTally and the "
                "original name is kept as provenance only"
            ),
        )
    extension = split_extension(filename)
    if extension not in ALLOWED_DOCUMENT_EXTENSIONS:
        raise HTTPException(
            status_code=422,
            detail=(
                f"'.{extension}' is not an allowed document extension"
                if extension
                else "the upload has no file extension"
            ),
        )
    if size_bytes <= 0:
        raise HTTPException(
            status_code=400, detail="size_bytes must be greater than zero"
        )
    limit_mb, limit_bytes = await _effective_limit_bytes(repos)
    if size_bytes > limit_bytes:
        raise HTTPException(
            status_code=413, detail=_oversize_detail(filename, size_bytes, limit_mb)
        )

    file_type = _classify(filename, content_type)
    try:
        path = build_document_storage_key(actor.organization_id, filename)
    except ValueError as exc:
        raise HTTPException(status_code=422, detail=f"invalid upload target: {exc}")
    mime_type = _renderable_content_type(filename, file_type, content_type)
    provenance = actor.provenance()
    # Advisory, best-effort document-type verdict.  It never gates the upload and
    # never changes what the processing pipeline is asked to do.
    classification = await _classify_upload(filename, document_type_code)
    record = await repos.files.create(
        org_id=actor.organization_id,
        name=sanitize_display_name(filename),
        path=path,
        size_bytes=size_bytes,
        file_type=file_type,
        mime_type=mime_type,
        bucket=DOCUMENTS_BUCKET,
        uploaded_by=actor.user_id,
        status=STATUS_PENDING_UPLOAD,
        metadata={
            "data_type": data_type,
            "file_url": path,
            "original_filename": filename,
            "upload_mode": "signed_direct",
            "security_gate": {"verdict": "pending", "scanner": None},
            # The classification verdict is persisted so it survives the upload and
            # is auditable even if the bytes never arrive (see abandon).
            "classification": classification,
            **provenance,
        },
    )
    document_id = str(_attr(record, "id") or "")

    signed = create_signed_upload_url(path)
    if not signed or not signed.get("url"):
        await _set_document_status(repos, document_id, STATUS_FAILED)
        await record_document_event(
            repos=repos,
            action=ACTION_UPLOAD_INITIATED,
            actor=actor,
            organization_id=actor.organization_id,
            entity_id=document_id,
            changed_fields={**provenance, "filename": filename, "storage_path": path},
            reason="no signed upload URL could be issued; the upload was not authorised",
            outcome="failure",
        )
        raise HTTPException(
            status_code=503,
            detail="storage upload authorisation is unavailable; nothing was accepted",
        )

    await record_document_event(
        repos=repos,
        action=ACTION_UPLOAD_INITIATED,
        actor=actor,
        organization_id=actor.organization_id,
        entity_id=document_id,
        changed_fields={
            **provenance,
            "filename": filename,
            "size_bytes": size_bytes,
            "declared_mime": content_type,
            "storage_path": path,
            "bucket": DOCUMENTS_BUCKET,
            "status": STATUS_PENDING_UPLOAD,
            "ingress": "signed_direct_upload",
            "signed_url_declared_ttl_seconds": SIGNED_UPLOAD_TTL_SECONDS,
        },
        reason="document upload initiated; short-lived signed upload URL issued",
    )
    return {
        "document_id": document_id,
        "organization_id": actor.organization_id,
        "client_id": client_id,
        "bucket": DOCUMENTS_BUCKET,
        "storage_path": path,
        "filename": filename,
        "status": STATUS_PENDING_UPLOAD,
        "upload_mode": "signed_direct",
        "max_size_bytes": limit_bytes,
        # CT-PO-UPLOAD-UNIFY-001 — the caller is told what CarbonTally classified
        # the document as, so a multi-file upload can report it per file.
        "classification": classification,
        # Step 2D — the caller is told exactly what will scan the bytes.  The
        # platform never implies a vendor malware scan it will not perform.
        "security_gate": external_scan_status(),
        "upload": {
            "url": signed["url"],
            "token": signed["token"],
            "method": "PUT",
            "expires_in_seconds": SIGNED_UPLOAD_TTL_SECONDS,
            "headers": {"x-upsert": "false", "content-type": mime_type},
        },
        "completion": {
            "method": "POST",
            "path": completion_path,
            "must_complete_within_seconds": UPLOAD_COMPLETION_WINDOW_SECONDS,
        },
        "resumable": {"supported": False, "reason": RESUMABLE_UNSUPPORTED_REASON},
    }



def _attr(record: Any, name: str, default: Any = None) -> Any:
    """Read a field from a domain object or a mapping (see v3_documents)."""
    if isinstance(record, dict):
        return record.get(name, default)
    return getattr(record, name, default)


async def _set_document_status(
    repos: Any, document_id: str, status: str, size_bytes: Optional[int] = None
) -> None:
    """Advance the document lifecycle state (best-effort, never fatal)."""
    update = getattr(getattr(repos, "files", None), "update_status", None)
    if not document_id or not callable(update):
        return
    try:
        if size_bytes is None:
            await update(document_id, status)
        else:
            await update(document_id, status, size_bytes)
    except Exception as exc:  # noqa: BLE001 - lifecycle bookkeeping is best-effort
        print(f"could not set document {document_id} status to {status}: {exc!r}")



async def _effective_limit_bytes(repos: Any) -> tuple[int, int]:
    """Return ``(limit_mb, limit_bytes)`` from the canonical upload policy."""
    policy = await resolve_policy(getattr(repos, "settings", None))
    limit_mb = policy["max_file_size_mb"]
    return limit_mb, effective_file_limit_bytes(limit_mb)


def _oversize_detail(filename: str, size_bytes: int, limit_mb: int) -> str:
    """Clear, actionable size error — the original is never compressed."""
    return (
        f"'{filename}' is {size_bytes / (1024 * 1024):.1f}MB; the platform limit "
        f"is {limit_mb}MB per file. The original document is never compressed "
        "server-side — please upload a smaller file or split the document."
    )


def _upload_window_expired(record: Any) -> bool:
    """Whether a ``pending_upload`` row is past its completion window.

    Rows without an ``uploaded_at`` value (in-memory/dev fixtures) are treated as
    fresh: the window is an abandonment rule for real uploads, not a way to
    reject anything the platform cannot date.
    """
    started = _attr(record, "uploaded_at")
    if not isinstance(started, datetime):
        return False
    if started.tzinfo is None:
        started = started.replace(tzinfo=timezone.utc)
    age = (datetime.now(timezone.utc) - started).total_seconds()
    return age > UPLOAD_COMPLETION_WINDOW_SECONDS

# ---------------------------------------------------------------------------
# advisory document-type classification
# ---------------------------------------------------------------------------
#
# Every uploaded file is classified against the EXISTING CarbonTally document
# taxonomy (``utils.document_classifier`` over the ``document_types`` reference
# table) so the user is told what CarbonTally believes the document is — without
# an upload-blocking "Data type" choice.
#
# The verdict is advisory and best-effort. The authoritative decision is still
# made downstream by extraction → mapping → validation, and an upload is never
# refused because the taxonomy could not be consulted.
#
# The processing pipeline is deliberately NOT influenced by this value:
# ``data_type`` (the processing hint passed to ``enqueue_document_processing``)
# keeps its existing value and behaviour.


def _unavailable_classification() -> dict:
    """The honest "not classified" verdict (never a fabricated type)."""
    return {
        "document_type_code": None,
        "document_type_id": None,
        "confidence": 0.0,
        "suggested_type": None,
        "category": None,
        "source": "unavailable",
        "alternative_types": [],
    }


async def _classify_upload(
    filename: str, document_type_code: Optional[str] = None
) -> dict:
    """Classify one uploaded file against the existing document taxonomy.

    ``document_type_code`` is an optional explicit choice; the classifier records
    it as ``source="user_selected"`` so an override is auditable.  When omitted
    the classifier decides from the document itself.

    Best-effort by design: the taxonomy is reference data that may not be
    configured in a given deployment, so a classification failure degrades to
    ``source="unavailable"`` rather than failing the upload.
    """
    try:
        return await classify_document(filename, None, document_type_code)
    except Exception as exc:  # noqa: BLE001 - classification is advisory
        print(f"⚠️ document classification unavailable for {filename}: {exc!r}")
        return _unavailable_classification()



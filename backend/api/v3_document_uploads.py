"""Storage Management Step 1C — direct-to-storage (signed) document upload.

The preferred upload pattern, implemented end to end server-side:

1. the browser asks CarbonTally to **start** an upload;
2. the backend authenticates and authorizes through the single upload gate
   (``api.upload_gate``) — organisation membership, or an active consultant
   grant plus the consultant's ``can_upload_documents`` capability;
3. the backend validates the proposed file name, extension, declared content
   type and size against the canonical admin-configurable upload policy;
4. the backend creates the ``organization_files`` row in ``pending_upload``;
5. the backend issues a **short-lived, object-scoped signed upload URL**;
6. the browser uploads the bytes **directly to Supabase Storage** — the backend
   never proxies the ordinary upload byte stream and never hands the
   service-role credential to the browser;
7. the browser confirms completion; the backend verifies the object exists,
   checks its real size, runs the security gate, and only then advances the
   document to ``clean`` and enqueues processing — or marks it ``rejected``
   (quarantined) and refuses it.

The storage path is **generated by CarbonTally** (``services.storage_keys``); a
client-supplied path is never accepted and the user file name is provenance
only.  A candidate upload is scoped to the client organisation's namespace —
there is no consultant bucket and no consultant-owned tenancy.

Resumable (TUS) uploads are deliberately not enabled in Step 1: the ratified
per-file cap is 10 MiB, an ordinary signed PUT covers that comfortably, and a
TUS session would require exposing a storage-level credential (project key or
user JWT) to the browser.  The response advertises this explicitly rather than
silently implying resumability.
"""

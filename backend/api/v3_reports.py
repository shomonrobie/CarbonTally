"""V3 reports surface (V3 Phase 5).

The org-scoped reporting workflow built on the authoritative chain:

    Source → Extraction → Mapping → Factor matching → Calculation engine
        → Validation → Review → Approval → REPORT

Reports are generated by the authoritative ``ReportGenerationEngine`` (the
same engine behind ``POST /api/v2/generate-report``) from the persisted
``emissions_logs`` / ``calculation_snapshots`` data. The frontend never
calculates or fabricates content; every response below reads the persisted
``report_generation_queue`` row (lifecycle, provenance, artefact state) and the
``generated_content`` JSONB written by the engine.

Lifecycle (preserving the existing synchronous architecture — no worker
infrastructure)::

    QUEUED (pending) → GENERATING (transient) → READY (completed)
    QUEUED (pending) → GENERATING (transient) → FAILED (failed + error_log)

Generation is synchronous inside the request: the queue row is created first
(QUEUED), moved to ``generating``, then the engine completes it (READY). On any
failure the real error is persisted to ``error_log`` and the row is marked
``failed`` — nothing is presented as ready unless the backend confirms the row
is ``completed`` with persisted content.

Versioning reuses the existing ``report_versions`` table (V3M2 schema): a
snapshot row is recorded on every successful generation.

Export reuses the existing org-isolated ``/api/v3/exports/*`` surface (CSV/JSON)
— no second export implementation.
"""
from __future__ import annotations

from typing import Any, Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import JSONResponse, Response
from pydantic import BaseModel, ConfigDict, Field

from api.consultant_branding import resolve_report_branding
from api.dependencies import (
    RepositoryBundle,
    ensure_org_access,
    get_report_engine,
    get_repositories,
    require_org_member,
)
from auth import AuthUser
from domain.report import ReportRequest
from engines.pdf_render import render_branded_pdf
from engines.report_generation import ReportGenerationEngine

router = APIRouter(prefix="/api/v3/reports", tags=["V3 — Reports"])

#: Report types the V3 engine genuinely supports. The engine composes one
#: structured 12-section report (annual emissions) from the persisted logs;
#: the legacy generator's other labels (summary/documents/staff/...) have no V3
#: engine backing and are deliberately not offered.
SUPPORTED_REPORT_TYPES: dict[str, str] = {
    "annual": "Annual emissions report (structured 12-section V3 report)",
}

#: Queue statuses surfaced by the dashboard (persisted values on the existing
#: ``report_generation_queue.status`` column).
REPORT_STATUSES: tuple[str, ...] = ("pending", "generating", "completed", "failed")

#: Human-readable display labels for persisted statuses.
STATUS_LABELS: dict[str, str] = {
    "pending": "Queued",
    "generating": "Generating",
    "completed": "Ready",
    "failed": "Failed",
}


class ReportGenerateIn(BaseModel):
    """Request to generate a report (client never supplies the result)."""

    organization_id: str = Field(..., min_length=1)
    report_type: str = "annual"
    reporting_year: int = Field(..., ge=1990, le=2100)
    template_id: Optional[str] = None
    options: dict[str, Any] = Field(default_factory=dict)

    model_config = ConfigDict(extra="forbid")


# ---------------------------------------------------------------------------
# Helpers (pure — unit-tested without a database)
# ---------------------------------------------------------------------------


def validate_report_type(report_type: str) -> None:
    """Reject report types with no V3 engine/data backing (HTTP 422)."""
    if report_type not in SUPPORTED_REPORT_TYPES:
        raise HTTPException(
            status_code=422,
            detail=(
                f"unsupported report type {report_type!r}; "
                f"supported: {', '.join(sorted(SUPPORTED_REPORT_TYPES))}"
            ),
        )


def validate_report_status(status: str) -> None:
    """Reject unknown status filters (HTTP 422)."""
    if status not in REPORT_STATUSES:
        raise HTTPException(
            status_code=422,
            detail=(
                f"unknown status {status!r}; "
                f"expected one of {', '.join(REPORT_STATUSES)}"
            ),
        )


def default_report_name(report_type: str, reporting_year: int) -> str:
    """Derive a display name from real report metadata (never fabricated)."""
    label = {
        "annual": "Annual emissions report",
    }.get(report_type, report_type.replace("_", " ").title())
    return f"{label} {reporting_year}"


def shape_report_status(report: dict) -> dict:
    """Attach the display label and ready flag for the dashboard.

    ``ready`` is derived from the persisted row state only: the report must be
    ``completed`` and carry persisted content/artefact details.
    """
    status = report.get("status") or "pending"
    content = report.get("generated_content") or {}
    ready = (
        status == "completed"
        and bool(content)
        and (bool(report.get("final_report_url")) or bool(report.get("page_count")))
    )
    return {
        **report,
        "status_label": STATUS_LABELS.get(status, status),
        "ready": ready,
    }


def shape_report_out(report: dict, current_version: Optional[dict] = None) -> dict:
    """Shape the API-facing report detail (lifecycle + provenance + version)."""
    shaped = shape_report_status(report)
    shaped["current_version"] = current_version or {}
    shaped["reporting_period"] = {
        "start_date": f"{report['reporting_year']}-01-01",
        "end_date": f"{report['reporting_year']}-12-31",
        "reporting_year": report["reporting_year"],
    }
    return shaped



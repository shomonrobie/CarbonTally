@router.get("/{report_id}/download")
async def download_report(
    report_id: str,
    current_user: AuthUser = Depends(require_org_member()),
    repos: RepositoryBundle = Depends(get_repositories),
) -> JSONResponse:
    """Secure download of the persisted report content (org-isolated).

    The report artefact is the structured ``generated_content`` JSONB written
    by the engine (no PDF rendering exists in V3 — documented backend gap). The
    content is served as a JSON attachment through the authenticated API only;
    no public storage URL is created.
    """
    report = await repos.reports.get_full(report_id)
    if report is None:
        raise HTTPException(status_code=404, detail="report not found")
    ensure_org_access(current_user, report["organization_id"])
    if report["status"] != "completed":
        raise HTTPException(
            status_code=409,
            detail=f"report is not ready (status={report['status']})",
        )
    content = report.get("generated_content") or {}
    if not content:
        raise HTTPException(status_code=404, detail="report has no generated content")
    payload = {
        "report_id": report_id,
        "organization_id": report["organization_id"],
        "report_type": report["report_type"],
        "reporting_year": report["reporting_year"],
        "status": "completed",
        "generated_at": report["completed_at"] or report["updated_at"],
        "content": content,
        # D21/D25: server-authorized presentation brand for this report
        # (CarbonTally / Consultant / Co-branded) so any downstream renderer
        # NEVER trusts a client-supplied consultant_id or brand input.
        "branding": (
            await resolve_report_branding(repos, current_user, report["organization_id"])
        ).to_dict(),
    }
    filename = report.get("final_report_file_name") or f"report-{report_id}.json"
    filename = report.get("final_report_file_name") or f"report-{report_id}.json"
    return JSONResponse(
        content=payload,
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


@router.get("/{report_id}/pdf")
async def download_report_pdf(
    report_id: str,
    current_user: AuthUser = Depends(require_org_member()),
    repos: RepositoryBundle = Depends(get_repositories),
) -> Response:
    """White-label PDF rendering (D27 / D19 §18).

    The PDF is rendered from the persisted structured report content plus the
    SERVER-authorized brand context (CarbonTally / consultant / co-branded).
    The brand is resolved from the authenticated relationship — a client-
    supplied brand is never accepted.
    """
    report = await repos.reports.get_full(report_id)
    if report is None:
        raise HTTPException(status_code=404, detail="report not found")
    ensure_org_access(current_user, report["organization_id"])
    if report["status"] != "completed":
        raise HTTPException(
            status_code=409,
            detail=f"report is not ready (status={report['status']})",
        )
    content = report.get("generated_content") or {}
    if not content:
        raise HTTPException(status_code=404, detail="report has no generated content")
    brand = await resolve_report_branding(
        repos, current_user, report["organization_id"]
    )
    try:
        pdf_bytes = render_branded_pdf(
            report={
                "report_type": report.get("report_type"),
                "reporting_year": report.get("reporting_year"),
            },
            content=content,
            brand=brand,
        )
    except Exception as exc:  # noqa: BLE001 — never leak renderer internals
        raise HTTPException(
            status_code=500, detail=f"report PDF rendering failed: {type(exc).__name__}"
        )
    filename = f"report-{report_id}-{brand.kind}.pdf"
    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )
    return JSONResponse(
        content=payload,
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )

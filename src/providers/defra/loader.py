def write_reports(result: ImportResult, output_dir: Path) -> list[str]:
    """Write the Markdown report set; returns the list of written paths."""
    report_dir = output_dir / "reports"
    report_dir.mkdir(parents=True, exist_ok=True)

    payloads: list[tuple[str, str]] = [
        ("workbook_analysis.md", _report_workbook_analysis(result)),
        ("worksheet_analysis.md", _report_worksheet_analysis(result)),
        ("mapping_report.md", _report_mapping(result)),
        ("validation_report.md", _report_validation(result)),
        ("import_summary.md", _report_summary(result)),
    ]

    written: list[str] = []
    for name, body in payloads:
        target = report_dir / name
        target.write_text(body, encoding="utf-8")
        written.append(str(target))
    logger.info("Markdown reports written to %s", report_dir)
    return written


def _report_workbook_analysis(result: ImportResult) -> str:
    meta = result.analysis.meta
    lines = [
        "# Workbook Analysis",
        "",
        "| Property | Value |",
        "|---|---|",
        f"| Source | `{meta.source_path}` |",
        f"| Size (bytes) | {meta.file_size_bytes} |",
        f"| SHA-256 | `{meta.file_sha256}` |",
        f"| Title | {meta.title} |",
        f"| Status | {meta.status} |",
        f"| Version | {meta.version} |",
        f"| Year | {meta.year} |",
        f"| Next publication date | {meta.next_publication_date} |",
        f"| Factor set (label) | {meta.factor_set_label} |",
        f"| Producer | {meta.producer} |",
        f"| Contact | {meta.contact} |",
        "",
        f"Reporting year resolved from the factor column header: **{result.analysis.reporting_year}**.",
        "",
        "## Worksheets",
        "",
        "| # | Worksheet | Type | Rows | Columns | Header row |",
        "|---|---|---|---|---|---|",
    ]
    for idx, ws in enumerate(result.analysis.worksheets, start=1):
        lines.append(
            f"| {idx} | {ws.name} | {ws.sheet_type} | {ws.max_row} | {ws.max_col} | {ws.header_row or '-'} |"
        )
    lines.append("")
    lines.append("## Data worksheets (contain emission factors)")
    if result.analysis.data_sheet_names:
        for name in result.analysis.data_sheet_names:
            lines.append(f"- `{name}`")
    else:
        lines.append("- *(none found)*")
    return "\n".join(lines)


def _report_worksheet_analysis(result: ImportResult) -> str:
    lines = ["# Worksheet Analysis", ""]
    for ws in result.analysis.worksheets:
        lines.append(f"## `{ws.name}`  —  type: `{ws.sheet_type}`")
        lines.append("")
        lines.append(f"- Rows: {ws.max_row}, Columns: {ws.max_col}")
        if ws.header_row:
            lines.append(f"- Data header row: {ws.header_row}")
        if ws.columns:
            lines.append("- Detected columns:")
            for label, idx in ws.columns:
                lines.append(f"  - `{label}` → column {idx}")
        if ws.data_row_count is not None:
            lines.append(f"- Rows below header: {ws.data_row_count}")
        if ws.notes:
            lines.append("- Notes:")
            for note in ws.notes:
                lines.append(f"  - {note}")
        lines.append("")
    return "\n".join(lines)



def _report_mapping(result: ImportResult) -> str:
    lines = [
        "# Mapping Report",
        "",
        f"Reporting year: **{result.analysis.reporting_year}**",
        "",
        "## Worksheets containing emission factors",
        "",
    ]
    for ws in result.analysis.worksheets:
        if ws.sheet_type != "data":
            continue
        lines.append(f"### `{ws.name}` (header row {ws.header_row})")
        lines.append("")
        lines.append("| Workbook column | Target DB field | Notes |")
        lines.append("|---|---|---|")
        for label, _idx in ws.columns:
            target = {
                "ID": "`defra_id` (reference only — no DB column)",
                "Scope": "`scope`",
                "Level 1": "`activity_type` (label component)",
                "Level 2": "`activity_type` (label component)",
                "Level 3": "`activity_type` (label component)",
                "Level 4": "`activity_type` (label component)",
                "Column Text": "`activity_type` (label component)",
                "UOM": "`unit`",
                "GHG/Unit": "`activity_type` (label component)",
            }.get(label)
            if target is None and label.startswith("GHG Conversion Factor"):
                target = "`co2e_multiplier` (exact decimal, unrounded)"
            if target is None:
                continue
            lines.append(f"| `{label}` | {target} | |")
        lines.append("")
    lines.append("## Constant values applied")
    lines.append("")
    lines.append("| DB field | Value |")
    lines.append("|---|---|")
    lines.append(f"| `reporting_year` | {result.config.get('reporting_year')} |")
    lines.append(f"| `factor_source` | `{result.config.get('factor_source')}` |")
    lines.append(f"| `factor_set` | `{result.config.get('factor_set')}` |")
    lines.append(f"| `country` | `{result.config.get('country')}` |")
    lines.append("")
    lines.append("## Natural key (idempotency)")
    lines.append("")
    lines.append(
        "`(reporting_year, activity_type, COALESCE(country,'GB'), "
        "COALESCE(unit,'{no-unit}'), COALESCE(scope,'{no-scope}'))`"
    )
    return "\n".join(lines)


def _report_validation(result: ImportResult) -> str:
    stats = result.stats
    lines = [
        "# Validation Report",
        "",
        f"Validated: **{stats.imported}** rows will be imported.",
        "",
        "## Totals",
        "",
        "| Metric | Count |",
        "|---|---|",
        f"| Rows scanned (data sheets) | {stats.rows_scanned} |",
        f"| Rows parsed | {stats.rows_parsed} |",
        f"| Rows with DEFRA ID | {stats.rows_with_id} |",
        f"| Rows with a published factor value | {stats.factors_with_value} |",
        f"| Imported | {stats.imported} |",
        f"| Skipped — no factor value | {stats.skipped_no_factor} |",
        f"| Skipped — unparseable factor | {stats.skipped_unparseable} |",
        f"| Skipped — no activity label | {stats.skipped_no_label} |",
        f"| Skipped — no DEFRA ID | {stats.skipped_no_id} |",
        f"| Skipped — validation error | {stats.skipped_validation} |",
        f"| Duplicates (natural key) | {stats.duplicates} |",
        "",
    ]
    warnings = [issue for issue in result.validation.issues if issue.severity == "warning"]
    if warnings:
        lines.append("## Findings (warnings)")
        lines.append("")
        lines.append("| Row | DEFRA ID | Field | Message |")
        lines.append("|---|---|---|---|")
        for issue in warnings:
            lines.append(
                f"| {issue.row_number} | {issue.defra_id} | `{issue.field}` | {issue.message} |"
            )
        lines.append("")
    return "\n".join(lines)


def _report_summary(result: ImportResult) -> str:
    lines = [
        "# Import Summary",
        "",
        f"Generated: {datetime.now().isoformat(timespec='seconds')}",
        "",
        "## Configuration",
        "",
        "| Option | Value |",
        "|---|---|",
    ]
    for key, value in result.config.items():
        lines.append(f"| {key} | `{value}` |")
    lines.append("")
    lines.append("## Statistics")
    lines.append("")
    lines.append("| Metric | Count |")
    lines.append("|---|---|")
    for key, value in result.stats.as_dict().items():
        lines.append(f"| {key} | {value} |")
    if result.db:
        lines.append("")
        lines.append("## Database result")
        lines.append("")
        lines.append("| Key | Value |")
        lines.append("|---|---|")
        for key, value in result.db.items():
            lines.append(f"| {key} | `{value}` |")
    return "\n".join(lines)



# ---------------------------------------------------------------------------
# Database loader
# ---------------------------------------------------------------------------
def load_to_db(
    factors: list[EmissionFactor],
    mode: str,
    db_url: Optional[str],
    supabase_url: Optional[str],
    supabase_key: Optional[str],
    schema: str = SCHEMA,
) -> dict[str, Any]:
    """Write factors to the database using the best available backend.

    Prefers a direct Postgres connection (psycopg2) when a DSN is supplied;
    falls back to the Supabase client (service role) when only
    ``SUPABASE_URL`` + ``SUPABASE_SERVICE_KEY`` are available.

    ``mode`` is ``sync`` (upsert by natural key) or ``replace`` (delete the
    factor set first, then insert — an exact, idempotent refresh).
    """
    if db_url:
        return load_with_psycopg2(factors, mode, db_url, schema)
    if supabase_url and supabase_key:
        return load_with_supabase(factors, mode, supabase_url, supabase_key)
    raise RuntimeError(
        "No database credentials available. Set DATABASE_URL (or SUPABASE_DB_URL/"
        "POSTGRES_URL) for a direct connection, or SUPABASE_URL + "
        "SUPABASE_SERVICE_KEY for the Supabase client."
    )


def load_with_psycopg2(
    factors: list[EmissionFactor],
    mode: str,
    dsn: str,
    schema: str = SCHEMA,
) -> dict[str, Any]:
    """Upsert factors through a direct Postgres connection in one transaction."""
    import psycopg2

    inserts = 0
    updates = 0
    deleted = 0
    table = f"{schema}.{TABLE}"
    conn = psycopg2.connect(dsn)
    try:
        with conn:
            with conn.cursor() as cur:
                if mode == "replace" and factors:
                    cur.execute(
                        f"DELETE FROM {table} WHERE factor_set = %s",
                        (factors[0].factor_set,),
                    )
                    deleted = cur.rowcount
                for factor in factors:
                    cur.execute(
                        "SELECT id FROM {table} WHERE "
                        "reporting_year = %s AND activity_type = %s AND "
                        "COALESCE(country, 'GB') = %s AND "
                        "COALESCE(unit, '{no_unit}') = %s AND "
                        "COALESCE(scope, '{no_scope}') = %s".format(
                            table=table, no_unit=NO_UNIT, no_scope=NO_SCOPE
                        ),
                        (
                            factor.reporting_year,
                            factor.activity_type,
                            factor.country or "GB",
                            factor.unit or NO_UNIT,
                            factor.scope or NO_SCOPE,
                        ),
                    )
                    existing = cur.fetchone()
                    if existing is not None:
                        cur.execute(
                            "UPDATE {table} SET co2e_multiplier = %s, unit = %s, "
                            "scope = %s, factor_source = %s, factor_set = %s, "
                            "country = %s, updated_at = NOW() WHERE id = %s".format(
                                table=table
                            ),
                            (
                                factor.co2e_multiplier,
                                factor.unit,
                                factor.scope,
                                factor.factor_source,
                                factor.factor_set,
                                factor.country,
                                existing[0],
                            ),
                        )
                        updates += 1
                    else:
                        cur.execute(
                            "INSERT INTO {table} (reporting_year, activity_type, "
                            "co2e_multiplier, unit, scope, factor_source, factor_set, "
                            "country) VALUES (%s, %s, %s, %s, %s, %s, %s, %s)".format(
                                table=table
                            ),
                            (
                                factor.reporting_year,
                                factor.activity_type,
                                factor.co2e_multiplier,
                                factor.unit,
                                factor.scope,
                                factor.factor_source,
                                factor.factor_set,
                                factor.country,
                            ),
                        )
                        inserts += 1
    finally:
        conn.close()
    return {
        "backend": "psycopg2",
        "mode": mode,
        "inserted": inserts,
        "updated": updates,
        "deleted_before_insert": deleted,
        "total_processed": len(factors),
    }



def load_with_supabase(
    factors: list[EmissionFactor],
    mode: str,
    url: str,
    key: str,
) -> dict[str, Any]:
    """Upsert factors through the Supabase client (service role)."""
    from supabase import create_client

    client = create_client(url.strip(), key.strip())
    table = client.table(TABLE)
    inserts = 0
    updates = 0
    deleted = 0

    if mode == "replace" and factors:
        result = table.delete().eq("factor_set", factors[0].factor_set).execute()
        deleted = len(result.data or [])

    for factor in factors:
        query = (
            table.select("id")
            .eq("reporting_year", factor.reporting_year)
            .eq("activity_type", factor.activity_type)
            .eq("country", factor.country or "GB")
        )
        if factor.unit is None:
            query = query.is_("unit", None)
        else:
            query = query.eq("unit", factor.unit)
        if factor.scope is None:
            query = query.is_("scope", None)
        else:
            query = query.eq("scope", factor.scope)

        result = query.maybe_single().execute()
        existing = result.data

        multiplier = format(factor.co2e_multiplier, "f")
        if existing:
            table.update(
                {
                    "co2e_multiplier": multiplier,
                    "unit": factor.unit,
                    "scope": factor.scope,
                    "factor_source": factor.factor_source,
                    "factor_set": factor.factor_set,
                    "country": factor.country,
                    "updated_at": datetime.now().isoformat(),
                }
            ).eq("id", existing["id"]).execute()
            updates += 1
        else:
            table.insert(
                {
                    "reporting_year": factor.reporting_year,
                    "activity_type": factor.activity_type,
                    "co2e_multiplier": multiplier,
                    "unit": factor.unit,
                    "scope": factor.scope,
                    "factor_source": factor.factor_source,
                    "factor_set": factor.factor_set,
                    "country": factor.country,
                }
            ).execute()
            inserts += 1

    return {
        "backend": "supabase",
        "mode": mode,
        "inserted": inserts,
        "updated": updates,
        "deleted_before_insert": deleted,
        "total_processed": len(factors),
    }


"""Artifact writers (JSON / SQL / Markdown reports) and database loader.

The SQL artifact is the canonical, portable deliverable: idempotent
``INSERT ... SELECT ... WHERE NOT EXISTS`` statements that match the RC2
natural-key unique index (``reporting_year, activity_type,
COALESCE(country,'GB'), COALESCE(unit,'{no-unit}'), COALESCE(scope,'{no-scope}')``)
so they are safe on both the narrow and widened index variants.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime
from decimal import Decimal
from pathlib import Path
from typing import Any, Optional

from .models import EmissionFactor, ImportResult

logger = logging.getLogger(__name__)

SCHEMA = "public"
TABLE = "emission_factors"
NO_UNIT = "{no-unit}"
NO_SCOPE = "{no-scope}"

# Query parameters psycopg2 understands; anything else (e.g. Supabase pooler's
# ``?schema=public``) is dropped so the DSN connects cleanly.
_PSYCOPG2_URI_PARAMS = {
    "sslmode", "sslrootcert", "sslcert", "sslkey", "sslpassword",
    "connect_timeout", "application_name", "options", "keepalives",
    "keepalives_idle", "target_session_attrs",
}


def _sanitize_dsn(dsn: str) -> str:
    """Return a psycopg2-compatible DSN (drops non-standard URI query params)."""
    if "?" not in dsn:
        return dsn
    base, _, query = dsn.partition("?")
    pairs = [
        item
        for item in query.split("&")
        if "=" in item and item.partition("=")[0] in _PSYCOPG2_URI_PARAMS
    ]
    return base + ("?" + "&".join(pairs) if pairs else "")


# ---------------------------------------------------------------------------
# SQL literal helpers
# ---------------------------------------------------------------------------
def _sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def _sql_nullable(value: Optional[str]) -> str:
    return "NULL" if value is None else _sql_str(value)


def _sql_decimal(value: Decimal) -> str:
    return format(value, "f")


# ---------------------------------------------------------------------------
# SQL generation
# ---------------------------------------------------------------------------
def generate_sql(factors: list[EmissionFactor], schema: str = SCHEMA) -> str:
    """Generate one idempotent INSERT statement per emission factor."""
    if not factors:
        return "-- No factors to import.\n"

    year = factors[0].reporting_year
    lines: list[str] = [
        "-- ============================================================================",
        f"-- CarbonTally — DEFRA {year} emission factors import (idempotent)",
        "-- Target table: public.emission_factors",
        f"-- Factor set: {factors[0].factor_set}  |  Source: {factors[0].factor_source}",
        "-- Generated by src.commands.import_defra at "
        + datetime.now().isoformat(timespec="seconds"),
        "-- Re-running this file never creates duplicate rows: each INSERT only",
        "-- fires when no row with the same natural key already exists.",
        "-- ============================================================================",
        "",
        "BEGIN;",
        "",
    ]

    for factor in factors:
        lines.extend(_insert_statement(factor, schema))

    lines.append("")
    lines.append("COMMIT;")
    return "\n".join(lines)


def _insert_statement(factor: EmissionFactor, schema: str) -> list[str]:
    year = factor.reporting_year
    unit_lit = factor.unit or NO_UNIT
    scope_lit = factor.scope or NO_SCOPE

    where = (
        "    SELECT 1 FROM {schema}.{table}\n"
        "     WHERE reporting_year = {year}\n"
        "       AND activity_type = {label}\n"
        "       AND COALESCE(country, 'GB') = {country}\n"
        "       AND COALESCE(unit, '{no_unit}') = {unit}\n"
        "       AND COALESCE(scope, '{no_scope}') = {scope}"
    ).format(
        schema=schema,
        table=TABLE,
        year=year,
        label=_sql_str(factor.activity_type),
        country=_sql_str(factor.country or "GB"),
        no_unit=NO_UNIT,
        unit=_sql_str(unit_lit),
        no_scope=NO_SCOPE,
        scope=_sql_str(scope_lit),
    )

    insert = (
        "INSERT INTO {schema}.{table}\n"
        "    (reporting_year, activity_type, co2e_multiplier, unit, scope,\n"
        "     factor_source, factor_set, country, updated_at)\n"
        "SELECT {year}, {label}, {multiplier}, {unit}, {scope},\n"
        "       {source}, {factor_set}, {country}, NOW()\n"
        "WHERE NOT EXISTS (\n{where}\n);"
    ).format(
        schema=schema,
        table=TABLE,
        year=year,
        label=_sql_str(factor.activity_type),
        multiplier=_sql_decimal(factor.co2e_multiplier),
        unit=_sql_nullable(factor.unit),
        scope=_sql_nullable(factor.scope),
        source=_sql_str(factor.factor_source),
        factor_set=_sql_str(factor.factor_set),
        country=_sql_str(factor.country or "GB"),
        where=where,
    )

    return [
        "-- DEFRA ID {id} | source row {row} | sheet {sheet}".format(
            id=factor.defra_id, row=factor.row_number, sheet=factor.sheet_name
        ),
        insert,
        "",
    ]


def write_sql_artifact(factors: list[EmissionFactor], output_dir: Path, suffix: str = "") -> str:
    """Write the SQL import file; returns its path."""
    sql_dir = output_dir / "sql"
    sql_dir.mkdir(parents=True, exist_ok=True)
    year = factors[0].reporting_year if factors else "unknown"
    path = sql_dir / f"import_defra_{year}{suffix}.sql"
    path.write_text(generate_sql(factors), encoding="utf-8")
    logger.info("SQL artifact written: %s", path)
    return str(path)


# ---------------------------------------------------------------------------
# JSON artifacts
# ---------------------------------------------------------------------------
def _dump_json(target: Path, data: Any) -> None:
    target.write_text(
        json.dumps(data, indent=2, ensure_ascii=False, default=str),
        encoding="utf-8",
    )


def write_json_artifacts(result: ImportResult, output_dir: Path) -> list[str]:
    """Write all JSON artifacts; returns the list of written paths."""
    json_dir = output_dir / "json"
    json_dir.mkdir(parents=True, exist_ok=True)

    payloads: list[tuple[str, Any]] = [
        ("workbook_analysis.json", result.analysis.as_dict()),
        ("worksheet_analysis.json", [w.as_dict() for w in result.analysis.worksheets]),
        ("mapping_report.json", _mapping_report_payload(result)),
        ("imported_rows.json", [f.as_dict() for f in result.validation.factors]),
        ("skipped_rows.json", [s.as_dict() for s in result.validation.skipped]),
        ("duplicates.json", [d.as_dict() for d in result.validation.duplicates]),
        ("validation_report.json", result.validation.as_dict()),
        (
            "import_summary.json",
            {
                "generated_at": datetime.now().isoformat(timespec="seconds"),
                "config": result.config,
                "stats": result.stats.as_dict(),
                "db": result.db,
            },
        ),
    ]

    written: list[str] = []
    for name, data in payloads:
        target = json_dir / name
        _dump_json(target, data)
        written.append(str(target))
    logger.info("JSON artifacts written to %s", json_dir)
    return written


def _mapping_report_payload(result: ImportResult) -> dict[str, Any]:
    data_sheets = [w for w in result.analysis.worksheets if w.sheet_type == "data"]
    return {
        "reporting_year": result.analysis.reporting_year,
        "data_sheets": [
            {
                "name": w.name,
                "header_row": w.header_row,
                "columns": [{"label": label, "index": idx} for label, idx in w.columns],
            }
            for w in data_sheets
        ],
        "column_mapping": {
            "ID": "defra_id (reference only — no DB column)",
            "Scope": "scope",
            "Level 1": "activity_type (label component)",
            "Level 2": "activity_type (label component)",
            "Level 3": "activity_type (label component)",
            "Level 4": "activity_type (label component)",
            "Column Text": "activity_type (label component)",
            "UOM": "unit",
            "GHG/Unit": "activity_type (label component)",
            "GHG Conversion Factor <year>": "co2e_multiplier",
            "reporting_year (from header)": "reporting_year",
        },
        "constant_values": {
            "factor_source": "DEFRA-DESNZ",
            "factor_set": "DEFRA-<year>",
            "country": "GB",
        },
    }


